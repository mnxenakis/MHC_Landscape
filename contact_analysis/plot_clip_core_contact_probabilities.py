def plot_panel(
    ax,
    summary: pd.DataFrame,
    chain_label: str,
    color: str,
    x_tick_fontsize: int,
    bold_labels: set[str] | None = None,
) -> None:
    sub = summary[summary["chain_label"] == chain_label].sort_values("residue_sort")
    x = np.arange(len(sub))
    labels = [tick_label(row.axis_label) for row in sub.itertuples(index=False)]

    ax.bar(
        x,
        sub["contact_probability"],
        color=to_rgba(CONTACT_PROBABILITY_BAR_COLOR, 0.50),
        edgecolor=to_rgba("black", 0.75),
        linewidth=0.45,
    )
    ax.set_ylim(0.0, 1.08)
    ax.set_ylabel("Contact probability")
    chain_symbol = r"$\alpha$" if chain_label == "alpha" else r"$\beta$"
    ax.set_xlabel(f"Consensus residue (chain {chain_symbol})")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=90, ha="center")
    for label in ax.get_xticklabels():
        if bold_labels and label.get_text() in bold_labels:
            label.set_fontweight("bold")
            label.set_color(uncommon_xtick_color(chain_label))
    ax.tick_params(axis="x", labelsize=x_tick_fontsize)
    ax.tick_params(axis="y", labelsize=22)
    if len(x):
        ax.set_xlim(-X_AXIS_EDGE_PADDING, len(x) - 1 + X_AXIS_EDGE_PADDING)
    ax.grid(axis="y", color="black", alpha=0.25, linestyle="--", lw=0.8)

    dist_ax = ax.twinx()
    y = sub["median_min_distance_angstrom"].to_numpy(dtype=float)
    q25 = sub["q25_min_distance_angstrom"].to_numpy(dtype=float)
    q75 = sub["q75_min_distance_angstrom"].to_numpy(dtype=float)
    dist_ax.fill_between(x, q25, q75, color="black", alpha=0.20, linewidth=0)
    dist_ax.plot(
        x,
        y,
        color="black",
        linewidth=1.6,
        marker="o",
        markerfacecolor=to_rgba("black", 0.30),
        markeredgecolor="black",
        markersize=4.5,
    )
    dist_ax.set_ylim(0.0, 5.2)
    dist_ax.set_ylabel("Minimum distance [Å]")
    dist_ax.tick_params(axis="y", labelsize=22)


def plot_core_panel(
    ax,
    summary: pd.DataFrame,
    chain_label: str,
    color: str,
    x_tick_fontsize: int,
    bold_labels: set[str] | None = None,
    contact_subset: str = "full",
) -> None:
    chain_rows = summary[summary["chain_label"] == chain_label]
    if contact_subset == "sub100":
        sub = chain_rows[chain_rows["contact_probability"] < 0.999999].sort_values("residue_sort")
        empty_text = "<100% contact residues"
        xlabel_text = "Consensus residue (<100% contact)"
    else:
        sub = chain_rows[chain_rows["contact_probability"] >= 0.999999].sort_values("residue_sort")
        empty_text = "100% contact residues"
        xlabel_text = "Consensus residue (100% contact)"
    sub = sub.copy()
    if sub.empty:
        ax.text(0.5, 0.5, f"No {empty_text}", ha="center", va="center", transform=ax.transAxes)
        ax.set_axis_off()
        return

    x = np.arange(len(sub))
    labels = [tick_label(row.axis_label) for row in sub.itertuples(index=False)]
    energy = sub["energy_total_median"].to_numpy(dtype=float)

    if contact_subset == "sub100":
        bar_color = SUB100_BAR_COLOR_ALPHA if chain_label == "alpha" else SUB100_BAR_COLOR_BETA
        ax.bar(
            x,
            sub["contact_probability"],
            color=to_rgba(bar_color, 0.50),
            edgecolor=to_rgba("black", 0.50),
            linewidth=0.40,
            zorder=1,
        )

    ax.fill_between(
        x,
        sub["energy_total_q1"],
        sub["energy_total_q3"],
        color="green",
        alpha=0.20,
        linewidth=0,
        zorder=3,
    )
    ax.plot(
        x,
        energy,
        color="green",
        linewidth=1.8,
        marker="o",
        markerfacecolor=to_rgba("green", 0.35),
        markeredgecolor="green",
        markersize=5.0,
        zorder=4,
    )
    ax.axhline(0.0, color="#008000", linestyle="--", lw=2.4, alpha=0.50, zorder=20)
    ax.set_ylabel("Consensus residue total energy [kcal/mol]")
    chain_symbol = r"$\alpha$" if chain_label == "alpha" else r"$\beta$"
    ax.set_xlabel(f"{xlabel_text} (chain {chain_symbol})")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=90, ha="center")
    for label in ax.get_xticklabels():
        if bold_labels and label.get_text() in bold_labels:
            label.set_fontweight("bold")
            label.set_color(uncommon_xtick_color(chain_label))
    ax.tick_params(axis="x", labelsize=x_tick_fontsize)
    ax.tick_params(axis="y", labelsize=22)
    if len(x):
        ax.set_xlim(-X_AXIS_EDGE_PADDING, len(x) - 1 + X_AXIS_EDGE_PADDING)
    ax.set_ylim(*ENERGY_TOTAL_YLIM)
    ax.grid(axis="y", color="black", alpha=0.25, linestyle="--", lw=0.8)

    dist_ax = ax.twinx()
    y = sub["median_min_distance_angstrom"].to_numpy(dtype=float)
    q25 = sub["q25_min_distance_angstrom"].to_numpy(dtype=float)
    q75 = sub["q75_min_distance_angstrom"].to_numpy(dtype=float)
    dist_ax.fill_between(x, q25, q75, color="black", alpha=0.20, linewidth=0)
    dist_ax.plot(
        x,
        y,
        color="black",
        linewidth=1.6,
        marker="o",
        markerfacecolor=to_rgba("black", 0.30),
        markeredgecolor="black",
        markersize=5.0,
    )
    dist_ax.set_ylim(0.0, 5.2)
    dist_ax.set_ylabel("Minimum distance [Å]")
    dist_ax.tick_params(axis="y", labelsize=22)


def plot_figure(
    summary: pd.DataFrame,
    out_pdf: Path,
    contact_mode: str,
    noncommon_labels: dict[str, set[str]] | None = None,
    alpha_beta_contact_subset: str = "full",
    xtick_fontsizes: dict[str, int] | None = None,
) -> None:
    plt.rcParams.update(
        {
            "font.family": "STIXGeneral",
            "mathtext.fontset": "stix",
            "text.usetex": False,
            "font.size": 18,
            "axes.labelsize": 32,
            "xtick.labelsize": 16,
            "ytick.labelsize": 22,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
        }
    )
    figsize = FIGSIZE_ALPHA_BETA_CORE if contact_mode == "alpha_beta_core" else FIGSIZE_CLIP_CORE
    fig, axes = plt.subplots(1, 2, figsize=figsize, constrained_layout=True)
    xtick_fontsizes = xtick_fontsizes or {}
    alpha_xtick_fontsize = xtick_fontsizes.get("alpha", xtick_fontsize(contact_mode, "alpha"))
    beta_xtick_fontsize = xtick_fontsizes.get("beta", xtick_fontsize(contact_mode, "beta"))
    if contact_mode == "alpha_beta_core":
        noncommon_labels = noncommon_labels or {"alpha": set(), "beta": set()}
        plot_core_panel(
            axes[0],
            summary,
            "alpha",
            "red",
            alpha_xtick_fontsize,
            noncommon_labels.get("alpha", set()),
            alpha_beta_contact_subset,
        )
        plot_core_panel(
            axes[1],
            summary,
            "beta",
            "blue",
            beta_xtick_fontsize,
            noncommon_labels.get("beta", set()),
            alpha_beta_contact_subset,
        )
    else:
        noncommon_labels = noncommon_labels or {"alpha": set(), "beta": set()}
        plot_panel(
            axes[0],
            summary,
            "alpha",
            "red",
            alpha_xtick_fontsize,
            noncommon_labels.get("alpha", set()),
        )
        plot_panel(
            axes[1],
            summary,
            "beta",
            "blue",
            beta_xtick_fontsize,
            noncommon_labels.get("beta", set()),
        )
    out_pdf.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_pdf, bbox_inches="tight")
    plt.close(fig)


