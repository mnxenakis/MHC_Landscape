def prepare_summary(
    args: argparse.Namespace,
    alpha_ref: featmap.ChainReference,
    beta_ref: featmap.ChainReference,
) -> tuple[pd.DataFrame, pd.DataFrame, str]:
    if not args.contacts_tsv.exists():
        raise SystemExit(f"Missing contact TSV: {args.contacts_tsv}")
    df = pd.read_csv(args.contacts_tsv, sep="\t")
    contact_mode = infer_contact_mode(df)
    if args.require_complete_alpha_panel:
        df = filter_to_complete_panel(df)
    df = map_contacts_to_consensus_axis(df, alpha_ref, beta_ref)
    summary = summarize_contacts(df)
    if contact_mode == "alpha_beta_core":
        energy_total = (
            load_energy_total_table(args.energy_total_tsv)
            if args.energy_total_tsv is not None
            else compute_rank_energy_total_table(args.energy_root, df)
        )
        summary = add_energy_total(summary, energy_total)
    return summary, df, contact_mode


def write_summary_and_plot(
    args: argparse.Namespace,
    summary: pd.DataFrame,
    mapped_contacts: pd.DataFrame,
    contact_mode: str,
) -> None:
    noncommon_labels: dict[str, set[str]] | None = None
    if contact_mode == "alpha_beta_core":
        noncommon_labels = noncommon_contact_labels(
            summary,
            mapped_contacts,
            contact_mode,
            args.alpha_beta_contact_subset,
        )
    elif contact_mode == "clip_core":
        noncommon_labels = noncommon_contact_labels(
            summary,
            mapped_contacts,
            contact_mode,
            args.alpha_beta_contact_subset,
        )
    args.out_tsv.parent.mkdir(parents=True, exist_ok=True)
    summary.to_csv(args.out_tsv, sep="\t", index=False)
    plot_figure(
        summary,
        args.out_pdf,
        contact_mode,
        noncommon_labels,
        args.alpha_beta_contact_subset,
        getattr(args, "xtick_fontsizes", None),
    )
    print(f"[write] {args.out_tsv}")
    print(f"[write] {args.out_pdf}")


def run_jobs(jobs: list[argparse.Namespace]) -> None:
    alpha_ref = featmap.load_reference_table(DEFAULT_ALPHA_REF, "A")
    beta_ref = featmap.load_reference_table(DEFAULT_BETA_REF, "B")
    prepared: list[tuple[argparse.Namespace, pd.DataFrame, pd.DataFrame, str]] = []

    # Write every summary first so paired-rank x-tick highlighting is available
    # even when the output directory starts clean.
    for args in jobs:
        summary, mapped_contacts, contact_mode = prepare_summary(args, alpha_ref, beta_ref)
        args.out_tsv.parent.mkdir(parents=True, exist_ok=True)
        summary.to_csv(args.out_tsv, sep="\t", index=False)
        prepared.append((args, summary, mapped_contacts, contact_mode))

    for args, summary, mapped_contacts, contact_mode in prepared:
        write_summary_and_plot(args, summary, mapped_contacts, contact_mode)


def main() -> int:
    if len(sys.argv) == 1:
        run_jobs(default_plot_jobs())
        return 0

    args = parse_args()
    alpha_ref = featmap.load_reference_table(args.alpha_ref, "A")
    beta_ref = featmap.load_reference_table(args.beta_ref, "B")
    summary, mapped_contacts, contact_mode = prepare_summary(args, alpha_ref, beta_ref)
    write_summary_and_plot(args, summary, mapped_contacts, contact_mode)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
