def parse_source_resnum(value: object) -> int | None:
    text = str(value or "").strip()
    if not text:
        return None
    try:
        return int(float(text))
    except Exception:
        return None


def filter_to_complete_panel(df: pd.DataFrame) -> pd.DataFrame:
    pairs = df[["heterodimer"]].drop_duplicates().copy()
    pairs["alpha_code"] = pairs["heterodimer"].str.split("_").str[0]
    counts = pairs.groupby("alpha_code")["heterodimer"].nunique()
    modal_count = int(counts.mode().iloc[0])
    keep_alpha = set(counts[counts == modal_count].index)
    return df[df["heterodimer"].str.split("_").str[0].isin(keep_alpha)].copy()


def map_contacts_to_consensus_axis(
    df: pd.DataFrame,
    alpha_ref: featmap.ChainReference,
    beta_ref: featmap.ChainReference,
) -> pd.DataFrame:
    """Map allele-specific PDB residue numbers onto the shared MSA axes."""
    mapped_parts: list[pd.DataFrame] = []
    failed = 0

    for heterodimer, hdf in df.groupby("heterodimer", sort=False):
        het = featmap.parse_heterodimer_codes(str(heterodimer), alpha_ref, beta_ref)
        for chain_label, allele_code, ref in (
            ("alpha", het.alpha, alpha_ref),
            ("beta", het.beta, beta_ref),
        ):
            sub = hdf.loc[hdf["chain_label"] == chain_label].copy()
            if sub.empty:
                continue

            seq = ref.allele_sequences[allele_code].copy()
            seq["source_resnum"] = seq["source_resnum"].astype(int)
            lookup = seq.set_index("source_resnum")[
                ["msa_resnum", "sort_value", "aa", "axis_label"]
            ]

            sub["source_resnum"] = sub["residue_id"].map(parse_source_resnum)
            sub = sub.dropna(subset=["source_resnum"]).copy()
            sub["source_resnum"] = sub["source_resnum"].astype(int)

            mapped = sub.join(lookup, on="source_resnum", how="left")
            failed += int(mapped["msa_resnum"].isna().sum())
            mapped = mapped.dropna(subset=["msa_resnum", "sort_value"]).copy()
            mapped["msa_resnum"] = mapped["msa_resnum"].astype(str)
            mapped["axis_label"] = mapped["axis_label"].astype(str)
            mapped_parts.append(mapped)

    if not mapped_parts:
        raise SystemExit("No contact rows could be mapped to the consensus residue axis.")

    out = pd.concat(mapped_parts, ignore_index=True)
    if failed:
        print(f"[warn] skipped {failed} contact row(s) that did not map to the consensus axis")
    return out


def summarize_contacts(df: pd.DataFrame) -> pd.DataFrame:
    n_heterodimers = df["heterodimer"].nunique()
    observation_cols = ["heterodimer"]
    if "rank" in df.columns:
        observation_cols.append("rank")
    total_observations = df[observation_cols].drop_duplicates().shape[0]
    grouped = (
        df.groupby(["chain_label", "msa_resnum", "axis_label", "sort_value"], as_index=False)
        .agg(
            n_heterodimers=("heterodimer", "nunique"),
            n_contact_observations=("heterodimer", "size"),
            source_residue_ids=("source_resnum", lambda x: "/".join(map(str, sorted(set(map(int, x)))))),
            residue_letters=("residue_one_letter", lambda x: "/".join(sorted(set(map(str, x))))),
            residue_names=("residue_name", lambda x: "/".join(sorted(set(map(str, x))))),
            median_min_distance_angstrom=("min_distance_angstrom", "median"),
            q25_min_distance_angstrom=("min_distance_angstrom", lambda x: x.quantile(0.25)),
            q75_min_distance_angstrom=("min_distance_angstrom", lambda x: x.quantile(0.75)),
        )
        .sort_values(["chain_label", "sort_value"])
    )
    grouped["n_total_heterodimers"] = n_heterodimers
    grouped["n_total_observations"] = total_observations
    grouped["contact_probability"] = grouped["n_contact_observations"] / total_observations
    grouped["residue_sort"] = grouped["sort_value"]
    return grouped.sort_values(["chain_label", "residue_sort"])


def rank_tag(rank: int) -> str:
    return f"rank_{rank:03d}" if rank < 1000 else f"rank_{rank}"


def single_rank(df: pd.DataFrame) -> int:
    ranks = sorted(pd.to_numeric(df["rank"], errors="coerce").dropna().astype(int).unique())
    if len(ranks) != 1:
        raise SystemExit(f"Expected exactly one rank in contact TSV, found: {ranks}")
    return int(ranks[0])


def rank_values(df: pd.DataFrame) -> list[int]:
    if "rank" not in df.columns:
        return []
    return sorted(pd.to_numeric(df["rank"], errors="coerce").dropna().astype(int).unique())


def interface_values_path(root: Path, heterodimer: str, reference_pdb: str) -> Path:
    alpha_code = heterodimer.split("_", 1)[0]
    results_dir = root / alpha_code / heterodimer / f"{heterodimer}_results"
    if reference_pdb.endswith("_Repair_chained.pdb"):
        filename = reference_pdb.replace("_Repair_chained.pdb", "_Repair_residue_values.tsv")
    else:
        filename = reference_pdb.replace(".pdb", "_residue_values.tsv")
    return results_dir / filename


def read_residue_values(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, sep="\t", comment="#")


def has_usable_energy_rows(df: pd.DataFrame) -> bool:
    needed = {"resname", "chain", "resnum", "total"}
    if not needed.issubset(df.columns):
        return False
    sub = df[list(needed)].copy()
    sub["chain"] = sub["chain"].astype(str).str.upper()
    sub = sub[sub["chain"].isin(["A", "B"])]
    sub["resnum"] = pd.to_numeric(sub["resnum"], errors="coerce")
    sub["total"] = pd.to_numeric(sub["total"], errors="coerce")
    sub = sub.dropna(subset=["resnum", "total", "resname"])
    return not sub.empty


def load_residue_values_with_fallback(path: Path) -> tuple[pd.DataFrame | None, Path | None, bool]:
    """Load residue energy rows, falling back to a non-empty re-repaired file if needed."""
    if path.exists():
        df = read_residue_values(path)
        if has_usable_energy_rows(df):
            return df, path, False

    fallback = path.with_name(path.name.replace("_Repair_residue_values.tsv", "_Repair_Repair_residue_values.tsv"))
    if fallback != path and fallback.exists():
        df = read_residue_values(fallback)
        if has_usable_energy_rows(df):
            return df, fallback, True

    return None, None, False


def standardize_energy_total_table(df: pd.DataFrame, source: str) -> pd.DataFrame:
    df = df.copy()
    if {"energy_total_median", "energy_total_q1", "energy_total_q3"}.issubset(df.columns):
        pass
    elif {"energy_total_median", "energy_total_min", "energy_total_max"}.issubset(df.columns):
        df = df.rename(columns={"energy_total_min": "energy_total_q1", "energy_total_max": "energy_total_q3"})
    else:
        raise SystemExit(
            f"{source} must contain signed energy_total_median with either "
            "energy_total_q1/energy_total_q3 or energy_total_min/energy_total_max."
        )

    required = {"chain", "resnum", "energy_total_median", "energy_total_q1", "energy_total_q3"}
    missing = required - set(df.columns)
    if missing:
        raise SystemExit(f"Missing column(s) in {source}: {sorted(missing)}")

    df["chain"] = df["chain"].astype(str).str.upper()
    df["resnum"] = pd.to_numeric(df["resnum"], errors="coerce").astype("Int64")
    for col in ("energy_total_median", "energy_total_q1", "energy_total_q3"):
        df[col] = pd.to_numeric(df[col], errors="coerce")
    return df.dropna(subset=["chain", "resnum", "energy_total_median"])


def load_energy_total_table(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise SystemExit(f"Missing residue-level energy_total TSV: {path}")
    df = pd.read_csv(path, sep="\t")
    return standardize_energy_total_table(df, str(path))


def compute_rank_energy_total_table(root: Path, contact_df: pd.DataFrame) -> pd.DataFrame:
    """Aggregate signed per-residue energy_total for the same rank and heterodimers as the contact TSV."""
    rank = single_rank(contact_df)
    rows: list[pd.DataFrame] = []
    missing: list[str] = []
    fallback_used: list[str] = []

    for heterodimer, hdf in contact_df.groupby("heterodimer", sort=False):
        refs = hdf["reference_pdb"].dropna().astype(str).unique()
        if len(refs) == 0:
            missing.append(heterodimer)
            continue
        path = interface_values_path(root, str(heterodimer), refs[0])
        loaded = load_residue_values_with_fallback(path)
        df, used_path, used_fallback = loaded
        if df is None or used_path is None:
            missing.append(str(heterodimer))
            continue
        if used_fallback:
            fallback_used.append(str(heterodimer))
        needed = {"resname", "chain", "resnum", "total"}
        if not needed.issubset(df.columns):
            continue
        df = df[list(needed)].copy()
        df["chain"] = df["chain"].astype(str).str.upper()
        df = df[df["chain"].isin(["A", "B"])]
        df["resnum"] = pd.to_numeric(df["resnum"], errors="coerce")
        df["total"] = pd.to_numeric(df["total"], errors="coerce")
        df = df.dropna(subset=["resnum", "total", "resname"])
        df["resnum"] = df["resnum"].astype(int)
        # Files can contain repeated identical residue rows; use one median value per residue per heterodimer.
        df = (
            df.groupby(["chain", "resnum", "resname"], as_index=False)["total"]
            .median()
            .rename(columns={"total": "energy_total"})
        )
        df["heterodimer"] = str(heterodimer)
        rows.append(df)

    if not rows:
        raise SystemExit(f"No signed energy_total rows found for rank {rank} under {root}")

    all_rows = pd.concat(rows, ignore_index=True)
    out = (
        all_rows.groupby(["chain", "resnum"], as_index=False)
        .agg(
            energy_total_median=("energy_total", "median"),
            energy_total_q1=("energy_total", lambda x: x.quantile(0.25)),
            energy_total_q3=("energy_total", lambda x: x.quantile(0.75)),
            energy_total_n=("energy_total", "size"),
            resnames=("resname", lambda x: "/".join(sorted(set(map(str, x))))),
        )
        .sort_values(["chain", "resnum"])
    )
    if missing:
        print(f"[warn] missing signed energy_total files for {len(missing)} heterodimer(s): {', '.join(missing[:10])}")
    if fallback_used:
        print(
            "[warn] used non-empty *_Repair_Repair_residue_values.tsv fallback for "
            f"{len(fallback_used)} heterodimer(s): {', '.join(fallback_used[:10])}"
        )
    print(f"[energy-total] rank={rank} heterodimers={all_rows['heterodimer'].nunique()} residues={len(out)}")
    return out


def add_energy_total(summary: pd.DataFrame, energy_total: pd.DataFrame) -> pd.DataFrame:
    """Attach residue-level energy_total using the same chain/residue numbering as plot_penalties.py."""
    energy_lookup = energy_total.set_index(["chain", "resnum"])

    def lookup_energy(row: pd.Series, col: str) -> float:
        chain = "A" if row["chain_label"] == "alpha" else "B"
        values = []
        for text in str(row["source_residue_ids"]).split("/"):
            try:
                key = (chain, int(float(text)))
            except ValueError:
                continue
            if key in energy_lookup.index:
                values.append(float(energy_lookup.loc[key, col]))
        return float(np.nanmedian(values)) if values else np.nan

    out = summary.copy()
    out["energy_total_median"] = out.apply(lambda row: lookup_energy(row, "energy_total_median"), axis=1)
    out["energy_total_q1"] = out.apply(lambda row: lookup_energy(row, "energy_total_q1"), axis=1)
    out["energy_total_q3"] = out.apply(lambda row: lookup_energy(row, "energy_total_q3"), axis=1)
    return out


def contact_labels_by_chain(summary: pd.DataFrame, contact_subset: str) -> dict[str, set[str]]:
    out: dict[str, set[str]] = {"alpha": set(), "beta": set()}
    if contact_subset == "full":
        sub = summary[summary["contact_probability"] >= 0.999999]
    elif contact_subset == "sub100":
        sub = summary[summary["contact_probability"] < 0.999999]
    else:
        sub = summary
    for chain_label, cdf in sub.groupby("chain_label"):
        out[str(chain_label)] = set(cdf["axis_label"].astype(str))
    return out


def rank_comparison_summary_path(contact_mode: str, rank: int) -> Path | None:
    if contact_mode == "clip_core":
        if rank == 1:
            return CLIP_HIGH_RANK_SUMMARY
        if rank == 1000:
            return CLIP_RANK001_SUMMARY
        return None
    if rank == 1:
        return ALPHA_BETA_RANK1000_SUMMARY
    if rank == 1000:
        return ALPHA_BETA_RANK001_SUMMARY
    return None


def noncommon_contact_labels(
    summary: pd.DataFrame,
    contact_df: pd.DataFrame,
    contact_mode: str,
    alpha_beta_contact_subset: str,
) -> dict[str, set[str]]:
    """Return plotted contact labels present in this rank but absent in the paired rank."""
    ranks = rank_values(contact_df)
    if contact_mode == "clip_core" and ranks == list(range(CLIP_HIGH_RANK_START, CLIP_HIGH_RANK_END + 1)):
        other_path = CLIP_RANK001_SUMMARY
    elif contact_mode == "clip_core" and ranks == [1]:
        other_path = CLIP_HIGH_RANK_SUMMARY
    elif contact_mode == "clip_core" and len(ranks) != 1:
        return {"alpha": set(), "beta": set()}
    else:
        rank = single_rank(contact_df)
        other_path = rank_comparison_summary_path(contact_mode, rank)
    if other_path is None or not other_path.exists():
        return {"alpha": set(), "beta": set()}

    contact_subset = alpha_beta_contact_subset if contact_mode == "alpha_beta_core" else "all"
    current = contact_labels_by_chain(summary, contact_subset=contact_subset)
    other = contact_labels_by_chain(pd.read_csv(other_path, sep="\t"), contact_subset=contact_subset)
    return {
        "alpha": current["alpha"] - other.get("alpha", set()),
        "beta": current["beta"] - other.get("beta", set()),
    }


